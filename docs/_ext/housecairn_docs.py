"""Sphinx extension of the HouseCairn documentation site (docs/adr/0016).

- Links from a page to a repository file outside `docs/` point to that file on
  GitHub, so the Markdown files keep working when browsed on GitHub.
- The OpenAPI schema is generated by `manage.py spectacular` at every build and
  rendered by the `openapi-reference` directive as static HTML.
- Every page gets a language switcher to the same page in the other language,
  and a notice when the page is not entirely translated.
"""

import json
import os
import posixpath
import re
import subprocess
import sys
from html import escape
from pathlib import Path
from typing import Any, ClassVar

from docutils import nodes
from sphinx.application import Sphinx
from sphinx.util.docutils import SphinxDirective

DOCS_DIR = Path(__file__).resolve().parents[1]
REPO_DIR = DOCS_DIR.parent
GENERATED_DIR = DOCS_DIR / "_generated"
SCHEMA_PATH = GENERATED_DIR / "openapi.json"
REPOSITORY_URL = "https://github.com/HouseCairn/housecairn/blob/main/"

# Language of each build and the path of its site below the root: English is
# the source, at the root; French is under /fr/.
LANGUAGES = {"en": ("English", ""), "fr": ("Français", "fr/")}
NOT_TRANSLATED = {
    "fr": (
        "Traduction incomplète",
        "Cette page n'est pas encore entièrement traduite : les passages non "
        "traduits sont affichés en anglais.",
    ),
}
HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")

# A Markdown link or image target: ](target) or ](target "title").
LINK_TARGET = re.compile(r"\]\((?P<target>[^)\s#]+)(?P<anchor>#[^)\s]*)?(?P<rest>[^)]*)\)")


def outside_link(docname: str, target: str) -> str | None:
    """GitHub URL of `target` if it is a relative path that leaves `docs/`."""
    if "://" in target or target.startswith(("/", "mailto:")):
        return None
    path = posixpath.normpath(posixpath.join(posixpath.dirname(docname), target))
    if not path.startswith("../"):
        return None
    return REPOSITORY_URL + path.removeprefix("../")


def rewrite_outside_links(app: Sphinx, docname: str, source: list[str]) -> None:
    def replace(match: re.Match[str]) -> str:
        url = outside_link(docname, match["target"])
        if url is None:
            return match.group(0)
        return f"]({url}{match['anchor'] or ''}{match['rest']})"

    source[0] = LINK_TARGET.sub(replace, source[0])


def generate_schema(app: Sphinx) -> None:
    """Write the OpenAPI schema of the application (manage.py spectacular)."""
    GENERATED_DIR.mkdir(exist_ok=True)
    env = {**os.environ, "DEBUG": "true", "PYTHONPATH": str(REPO_DIR / "src")}
    env.setdefault("HOUSECAIRN_DATA_DIR", str(GENERATED_DIR / "data"))
    command = [
        sys.executable,
        str(REPO_DIR / "manage.py"),
        "spectacular",
        "--format",
        "openapi-json",
        "--validate",
        "--fail-on-warn",
        "--file",
        str(SCHEMA_PATH),
    ]
    subprocess.run(command, check=True, cwd=REPO_DIR, env=env)  # noqa: S603


def _text(text: str, node_class: type[nodes.TextElement] = nodes.paragraph) -> nodes.Element:
    node = node_class(text, text)
    # Generated from the code: not in the translation catalogs.
    node["translatable"] = False
    return node


def _table(header: list[str], rows: list[list[str]]) -> nodes.table:
    table = nodes.table(classes=["openapi-table"])
    group = nodes.tgroup(cols=len(header))
    table += group
    group += [nodes.colspec(colwidth=1) for _ in header]
    head = nodes.thead()
    group += head
    body = nodes.tbody()
    group += body
    for target, cells in ((head, [header]), (body, rows)):
        for cells_of_row in cells:
            row = nodes.row()
            for cell in cells_of_row:
                entry = nodes.entry()
                entry += _text(cell)
                row += entry
            target += row
    return table


def schema_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "allOf" in schema:
        return " & ".join(schema_type(s) for s in schema["allOf"])
    if "oneOf" in schema or "anyOf" in schema:
        return " | ".join(schema_type(s) for s in schema.get("oneOf", schema.get("anyOf", [])))
    kind = schema.get("type", "object")
    if isinstance(kind, list):
        kind = " | ".join(str(k) for k in kind)
    if kind == "array":
        return f"array of {schema_type(schema.get('items', {}))}"
    if "format" in schema:
        return f"{kind} ({schema['format']})"
    return str(kind)


def operations(schema: dict[str, Any]) -> list[tuple[str, str, dict[str, Any]]]:
    """(method, path, operation) of every operation of the schema, in order."""
    found = []
    for path, item in schema.get("paths", {}).items():
        for method in HTTP_METHODS:
            if method in item:
                found.append((method, path, item[method]))
    return found


class OpenAPIReference(SphinxDirective):
    """Render every operation and schema of the generated OpenAPI document."""

    has_content = False
    option_spec: ClassVar[dict[str, Any]] = {}

    def run(self) -> list[nodes.Node]:
        self.env.note_dependency(str(SCHEMA_PATH))
        schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
        result: list[nodes.Node] = []
        for method, path, operation in operations(schema):
            result.append(self.operation(method, path, operation))
        components = schema.get("components", {}).get("schemas", {})
        if components:
            result.append(_text("Schemas", nodes.rubric))
            for name, component in components.items():
                result.append(self.component(name, component))
        return result

    def operation(self, method: str, path: str, operation: dict[str, Any]) -> nodes.Element:
        operation_id = operation.get("operationId", f"{method}-{path}")
        box = nodes.container(classes=["openapi-operation"], ids=[f"operation-{operation_id}"])
        title = nodes.rubric(classes=["openapi-title"])
        title["translatable"] = False
        title += nodes.literal(text=f"{method.upper()} {path}")
        box += title
        box += _text(f"Operation: {operation_id}")
        for text in (operation.get("summary"), operation.get("description")):
            if text:
                box += _text(" ".join(str(text).split()))
        parameters = operation.get("parameters", [])
        if parameters:
            rows = [
                [
                    p.get("name", ""),
                    p.get("in", ""),
                    "yes" if p.get("required") else "no",
                    schema_type(p.get("schema", {})),
                    " ".join(str(p.get("description", "")).split()),
                ]
                for p in parameters
            ]
            box += _table(["Parameter", "In", "Required", "Type", "Description"], rows)
        body = operation.get("requestBody", {}).get("content", {})
        if body:
            rows = [[media, schema_type(c.get("schema", {}))] for media, c in body.items()]
            box += _table(["Request body", "Schema"], rows)
        responses = operation.get("responses", {})
        if responses:
            rows = []
            for code, response in responses.items():
                content = response.get("content", {})
                types = ", ".join(schema_type(c.get("schema", {})) for c in content.values())
                rows.append([str(code), str(response.get("description", "")), types])
            box += _table(["Response", "Description", "Schema"], rows)
        return box

    def component(self, name: str, component: dict[str, Any]) -> nodes.Element:
        box = nodes.container(classes=["openapi-schema"], ids=[f"schema-{name}"])
        title = nodes.rubric()
        title["translatable"] = False
        title += nodes.literal(text=name)
        box += title
        required = set(component.get("required", []))
        rows = [
            [
                prop,
                schema_type(spec),
                "yes" if prop in required else "no",
                "yes" if spec.get("readOnly") else "no",
            ]
            for prop, spec in component.get("properties", {}).items()
        ]
        if rows:
            box += _table(["Field", "Type", "Required", "Read-only"], rows)
        elif "enum" in component:
            box += _text("Values: " + ", ".join(str(v) for v in component["enum"]))
        return box


def page_context(
    app: Sphinx,
    pagename: str,
    templatename: str,
    context: dict[str, Any],
    doctree: nodes.document | None,
) -> None:
    """Language switcher links, and the notice of an incomplete translation."""
    language = app.config.language
    target = app.builder.get_target_uri(pagename)
    depth = target.count("/")
    # Root of the whole site, relative to this page.
    to_root = "../" * (depth + (1 if LANGUAGES[language][1] else 0)) or "./"
    page = "" if target in ("", "index", "index/") else target
    context["hc_languages"] = [
        {
            "code": code,
            "label": label,
            "url": to_root + prefix + page,
            "current": code == language,
        }
        for code, (label, prefix) in LANGUAGES.items()
    ]
    if language == "en" or doctree is None or "body" not in context:
        return
    progress = doctree.get("translation_progress", {"total": 0, "translated": 0})
    if progress["total"] == 0 or progress["translated"] < progress["total"]:
        title, notice = NOT_TRANSLATED[language]
        context["body"] = (
            f'<div class="admonition note translation-notice" role="note">'
            f'<p class="admonition-title">{escape(title)}</p>'
            f"<p>{escape(notice)}</p></div>\n" + context["body"]
        )


def setup(app: Sphinx) -> dict[str, Any]:
    app.connect("source-read", rewrite_outside_links)
    app.connect("builder-inited", generate_schema)
    app.connect("html-page-context", page_context)
    app.add_directive("openapi-reference", OpenAPIReference)
    return {"version": "1", "parallel_read_safe": True, "parallel_write_safe": True}
