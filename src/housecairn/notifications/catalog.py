    schemes: tuple[str, ...]
    example: str
    where: str
    # The name of the page of the service in the documentation of Apprise.
    page: str

    @property
    def link(self) -> str:
        return f"https://appriseit.com/services/{self.page}/"

    @property
    def where_label(self) -> Promise:
        return WHERE[self.where]


