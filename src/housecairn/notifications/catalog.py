"""The services a channel may use, by family, with an example address (docs/adr/0064).

Each one was reviewed in the version of Apprise of `uv.lock`: its plugin speaks HTTP(S) or
SMTP, fixes the method and the format of every request, and no option of its address
chooses the method, the path, the headers or the fields. The schemes of these services
are the only ones `outbound` accepts; ADR 0064 lists every other plugin and why it is
refused.

`where` says where a message goes: `self` (a server that the person runs, or chooses),
`region` (the provider, in the region that the address chooses), `eu` (the provider, in
the European Union), `elsewhere` (the provider, outside the European Union, or without
saying where).
"""

