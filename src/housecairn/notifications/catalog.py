def by_family() -> list[tuple[str, Promise, list[Service]]]:
    """The services grouped by family, in the order of `FAMILIES`, each sorted by name."""
    return [
        (key, label, sorted((s for s in SERVICES if s.family == key), key=lambda s: s.name.lower()))
        for key, label in FAMILIES.items()
    ]
